// Builds src/lib/lookalikes.ts, the letters from every script that look like
// a Latin letter, for names.ts nameSkeleton: from Unicode's confusables.txt
// (UTS #39), each character that looks like one or two Latin letters or
// digits, as nameSkeleton sees it (NFKD, lowercase), and isn't one already.
// Run: node scripts/make-lookalikes.mjs path/to/confusables.txt
// (https://www.unicode.org/Public/security/latest/confusables.txt)
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.error('Usage: node scripts/make-lookalikes.mjs path/to/confusables.txt');
  process.exit(1);
}
const text = readFileSync(src, 'utf8');
const version = /^# Date: (.*)$/m.exec(text)?.[1] ?? '?';
// As nameSkeleton folds digits that pass for letters.
const DIGITS = { 0: 'o', 1: 'l', 3: 'e', 4: 'a', 5: 's', 7: 't', 8: 'b' };
const seen = (s) => s.normalize('NFKD').toLowerCase().replace(/\p{M}/gu, '');
// Unicode draws many letters' look-alikes as Latin small capitals (в → ʙ): those count as their letter.
const smallCapital = new Map();
for (const m of text.matchAll(/^([0-9A-F]+) ;\t([0-9A-F ]+?) ;.*\) .* → (.*?)\t#/gm)) {
  const names = m[3].split(', ');
  const points = m[2].split(' ');
  points.forEach((h, i) => {
    const letter = /^LATIN LETTER SMALL CAPITAL ([A-Z])$/.exec(names[i] ?? '')?.[1];
    if (letter) smallCapital.set(String.fromCodePoint(parseInt(h, 16)), letter.toLowerCase());
  });
}
const letterOf = (c) => smallCapital.get(c) ?? DIGITS[c] ?? c;
/** Each character's letters: one already lower case (as nameSkeleton meets it) wins over another's lower case. */
const found = new Map();
const add = (raw, from, to) => {
  const own = raw.toLowerCase() === raw;
  const was = found.get(from);
  if (!was || (own && !was.own)) found.set(from, { to, own });
};
for (const [c, to] of smallCapital) add(c, seen(c), to);
for (const line of text.split('\n')) {
  const m = /^([0-9A-F]+)\s*;\s*([0-9A-F ]+?)\s*;/.exec(line);
  if (!m) continue;
  const raw = String.fromCodePoint(parseInt(m[1], 16));
  const from = seen(raw);
  const to = Array.from(m[2].split(' ').map((h) => String.fromCodePoint(parseInt(h, 16))).join(''), (c) => (smallCapital.get(c) ?? seen(c)))
    .join('')
    .split('')
    .map(letterOf)
    .join('');
  // One letter or digit as nameSkeleton meets it (signs and lines are no part of a name's look there), standing for one or two letters it isn't already.
  if (Array.from(from).length !== 1 || !/[\p{L}\p{N}]/u.test(from) || !/^[a-z]{1,2}$/.test(to) || /[a-z0-9]/.test(from)) continue;
  add(raw, from, to);
}
const byTarget = new Map();
for (const [from, { to }] of found) {
  if (!byTarget.has(to)) byTarget.set(to, new Set());
  byTarget.get(to).add(from);
}
const rows = [...byTarget]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([to, from]) => `  ${/^[a-z]+$/.test(to) ? to : `'${to}'`}: ${JSON.stringify([...from].sort().join(''))},`);
const out = `// Generated by scripts/make-lookalikes.mjs from Unicode's confusables.txt (${version}); don't edit by hand.
// For each Latin letter (or two), the characters from other scripts that look like it.

export const LOOKALIKES: Record<string, string> = {
${rows.join('\n')}
};

const LETTER_OF = new Map(Object.entries(LOOKALIKES).flatMap(([to, from]) => Array.from(from, (c) => [c, to] as const)));

/** The Latin letters a look-alike (as NFKD and lower case leave it) passes for; undefined for anything else. */
export const lookalikeOf = (c: string) => LETTER_OF.get(c);

/** Each look-alike in \`s\` read as its Latin letters, upper case where it was. */
export function foldLookalikes(s: string): string {
  return Array.from(s, (c) => {
    const to = LETTER_OF.get(c.toLowerCase());
    return to === undefined ? c : c === c.toLowerCase() ? to : to.toUpperCase();
  }).join('');
}
`;
writeFileSync(new URL('../src/lib/lookalikes.ts', import.meta.url), out);
console.log(`${[...byTarget.values()].reduce((n, s) => n + s.size, 0)} characters, ${byTarget.size} letters`);
