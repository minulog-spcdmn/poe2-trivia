// Writes counts/botRanges.js: the cloud and hosting providers' address ranges
// GoatCounter calls a count from a bot by (zgo.at/isbot's ip_ranges.go, at
// the version GoatCounter's own go.mod names, ISBOT below), so the counts
// Worker can tell GoatCounter what its /count works out for itself: its API,
// which the Worker sends to, checks a count's browser string only
// (counts/worker.js, `botOf`). Run it again when GoatCounter moves to a newer
// isbot: `node scripts/bot-ranges.mjs`.
//
// Each range as isbot has it, a provider's prefix; those of one provider that
// touch merged into one (no two providers' overlap: the script stops if they
// do), sorted, as little-endian 32-bit words in base64: an IPv4 range's first
// and last address, an IPv6 range's in four words each, highest first. With
// each range, isbot's code for its provider (isbot.go, BotRange…), which
// GoatCounter keeps as the bot it was.

import { writeFileSync } from 'node:fs';

const ISBOT = 'v1.1.0';
const RAW = `https://raw.githubusercontent.com/arp242/isbot/${ISBOT}`;
const OUT = new URL('../counts/botRanges.js', import.meta.url);

/** A file from isbot at ISBOT; tried again once after a pause if GitHub turns it away. */
async function get(name) {
  for (let i = 0; ; i++) {
    const r = await fetch(`${RAW}/${name}`, { headers: { 'User-Agent': 'bot-ranges-script' } });
    if (r.ok) return r.text();
    if (i) throw new Error(`${name}: ${r.status}`);
    await new Promise((ok) => setTimeout(ok, 10_000));
  }
}

const [ranges, ip, isbot] = await Promise.all([get('ip_ranges.go'), get('ip.go'), get('isbot.go')]);

// A provider's name in ip_ranges.go, to its constant (ip.go botname), to its code (isbot.go).
const codes = new Map([...isbot.matchAll(/^\s*(BotRange\w+)\s*=\s*(\d+)/gm)].map((m) => [m[1], Number(m[2])]));
const names = new Map([...ip.matchAll(/case "(\w+)":\s*return (BotRange\w+)/g)].map((m) => [m[1], codes.get(m[2])]));
if (!names.size || [...names.values()].some((c) => !c)) throw new Error('isbot: providers not read');

/** An address as a number (BigInt): IPv4 in 32 bits, IPv6 in 128. */
function number(addr, v6) {
  if (!v6) return addr.split('.').reduce((n, p) => (n << 8n) | BigInt(Number(p)), 0n);
  const [head, tail = ''] = addr.split('::');
  const left = head ? head.split(':') : [];
  const right = tail ? tail.split(':') : [];
  const groups = addr.includes('::') ? [...left, ...Array(8 - left.length - right.length).fill('0'), ...right] : left;
  if (groups.length !== 8) throw new Error(`not an address: ${addr}`);
  return groups.reduce((n, g) => (n << 16n) | BigInt(parseInt(g, 16)), 0n);
}

/** One family's ranges, merged and sorted: [first, last, code]. */
function family(name, bits) {
  const list = ranges.match(new RegExp(`${name} = \`([^\`]*)\``))?.[1];
  if (!list) throw new Error(`${name} not found`);
  const all = list
    .trim()
    .split(/\s+/)
    .map((f) => {
      const [prefix, provider] = f.split(',');
      const [addr, len] = prefix.split('/');
      const size = 1n << BigInt(bits - Number(len));
      const first = number(addr, bits === 128) & ~(size - 1n);
      const code = names.get(provider);
      if (!code) throw new Error(`unknown provider ${provider}`);
      return [first, first + size - 1n, code];
    })
    .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const merged = [];
  for (const r of all) {
    const last = merged.at(-1);
    if (last && r[0] <= last[1] && r[2] !== last[2]) throw new Error(`${name}: two providers overlap`);
    if (last && r[2] === last[2] && r[0] <= last[1] + 1n) last[1] = r[1] > last[1] ? r[1] : last[1];
    else merged.push([...r]);
  }
  return merged;
}

/** Ranges as base64: their bounds in 32-bit words (`words` each), and their codes. */
function pack(list, words) {
  const bounds = Buffer.alloc(list.length * words * 8);
  let at = 0;
  for (const [first, last] of list)
    for (const n of [first, last])
      for (let w = words - 1; w >= 0; w--) at = bounds.writeUInt32LE(Number((n >> BigInt(32 * w)) & 0xffffffffn), at);
  return { bounds: bounds.toString('base64'), codes: Buffer.from(list.map((r) => r[2])).toString('base64') };
}

const v4 = family('ranges4', 32);
const v6 = family('ranges6', 128);
const p4 = pack(v4, 1);
const p6 = pack(v6, 4);
writeFileSync(
  OUT,
  `// Generated by scripts/bot-ranges.mjs from zgo.at/isbot ${ISBOT} (ip_ranges.go): don't edit.
// ${v4.length} IPv4 and ${v6.length} IPv6 ranges, read by counts/worker.js (botOf).
export const ISBOT = '${ISBOT}';
export const V4 = '${p4.bounds}';
export const V4_CODES = '${p4.codes}';
export const V6 = '${p6.bounds}';
export const V6_CODES = '${p6.codes}';
`,
);
console.log(`counts/botRanges.js: ${v4.length} IPv4 and ${v6.length} IPv6 ranges from isbot ${ISBOT}`);
